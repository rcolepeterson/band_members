// ----------------------------------------------------------------------
// 2. It is an overlay, not SVG content.
// ----------------------------------------------------------------------

test('empty state is a DOM sibling of #graph-svg, not SVG content', () => {
  // #graph-svg must stay an empty element in the static markup — everything
  // inside it is generated by D3 and cleared on every render.
  assert.match(
    INDEX_HTML,
    /<svg id="graph-svg"[^>]*><\/svg>/,
    'Expected #graph-svg to remain empty in the static markup. If the empty ' +
      'state were nested inside it, graphGroup.selectAll("*").remove() would ' +
      'delete it on the next render.'
  );

  // Positive placement check: the card sits between the <svg> and the stats
  // badge, both of which are direct children of .graph-stage. That pins it
  // to the overlay layer without depending on brittle nesting regexes.
  const svgIndex = INDEX_HTML.indexOf('<svg id="graph-svg"');
  const emptyStateIndex = INDEX_HTML.indexOf('<div class="graph-empty-state" id="graph-empty-state"');
  const badgeIndex = INDEX_HTML.indexOf('<div class="graph-stats-badge" id="graph-stats-badge"');
  assert.ok(svgIndex > -1, 'Expected #graph-svg in index.html.');
  assert.ok(emptyStateIndex > -1, 'Expected the #graph-empty-state div in index.html.');
  assert.ok(badgeIndex > -1, 'Expected #graph-stats-badge in index.html.');
  assert.ok(
    svgIndex < emptyStateIndex && emptyStateIndex < badgeIndex,
    'Expected #graph-empty-state to sit between #graph-svg and ' +
      '#graph-stats-badge inside .graph-stage — i.e. in the same DOM overlay ' +
      'layer as the rest of the HUD, so its visibility is independent of what ' +
      'renderGraph() does to the SVG.'
  );
});

test('empty-state CSS positions it over the stage above the graph', () => {
  const ruleMatch = INDEX_HTML.match(/\.graph-empty-state\s*\{([^}]+)\}/);
  assert.ok(ruleMatch, 'Expected a .graph-empty-state CSS rule.');
  const rule = ruleMatch[1];
  assert.match(
    rule,
    /position:\s*absolute/,
    'The empty state must be position:absolute so it centers inside the ' +
      'position:relative .graph-stage.'
  );
  const zIndexMatch = rule.match(/z-index:\s*(\d+)/);
  assert.ok(zIndexMatch, 'Expected an explicit z-index on .graph-empty-state.');
  // .graph-stage is z-index 0 and #graph-badge is 9; the popovers are 15 and
  // the mobile sheet is 70. The card has to clear the graph without covering
  // the Add-band popover it opens.
  const zIndex = Number(zIndexMatch[1]);
  assert.ok(
    zIndex > 9 && zIndex < 15,
    `Expected .graph-empty-state z-index between 10 and 14 (got ${zIndex}). ` +
      'Below 10 it can be painted under the graph chrome; 15 or above and it ' +
      'covers the Add-band popover the CTA opens.'
  );
});

// ----------------------------------------------------------------------
// 3. Mobile parity.
// ----------------------------------------------------------------------

test('empty state renders on mobile too (not inside .graph-overlay-top, never display:none)', () => {
  // .graph-overlay-top is display:none under 900px. Anything the mobile user
  // needs cannot live inside it — that's the PR #42/#44 bug.
  const overlayTopIndex = INDEX_HTML.indexOf('<div class="graph-overlay graph-overlay-top">');
  const emptyStateIndex = INDEX_HTML.indexOf('<div class="graph-empty-state" id="graph-empty-state"');
  assert.ok(overlayTopIndex > -1, 'Expected .graph-overlay-top in index.html.');
  assert.ok(
    emptyStateIndex > overlayTopIndex,
    'Sanity check on markup order: the empty state should come after the ' +
      '.graph-overlay-top block, alongside the SVG.'
  );
  // The toolbar's own popovers close before </div> of .graph-overlay-top, and
  // the SVG (a stage-level sibling) sits between it and the empty state — so
  // if #graph-svg is between them, the empty state is outside the overlay.
  const svgIndex = INDEX_HTML.indexOf('<svg id="graph-svg"');
  assert.ok(
    overlayTopIndex < svgIndex && svgIndex < emptyStateIndex,
    'Expected #graph-svg to sit between .graph-overlay-top and ' +
      '#graph-empty-state, which proves the empty state is not nested inside ' +
      'the desktop-only overlay (display:none under 900px).'
  );

  // And no media query may hide it.
  assert.ok(
    !/@media[^{]*\{[^}]*\.graph-empty-state[^}]*display:\s*none/.test(INDEX_HTML),
    'No media query may set display:none on .graph-empty-state. The empty ' +
      'state must reach mobile visitors — they are the ones most likely to ' +
      'mistype a band name.'
  );
});

// ----------------------------------------------------------------------
// 4. Show / hide logic.
// ----------------------------------------------------------------------

test('syncSearchEmptyState shows the card only for a non-empty search with zero matches', () => {
  const fnMatch = INDEX_HTML.match(
    /function\s+syncSearchEmptyState\s*\(\s*matchCount\s*\)\s*\{([\s\S]*?)\n\s{4}\}/
  );
  assert.ok(fnMatch, 'Expected function syncSearchEmptyState(matchCount) in index.html.');
  const body = fnMatch[1];

  // Both conditions, ANDed. currentSearch alone would fire the card on a
  // successful search; matchCount alone would fire it when a scene/genre
  // filter empties the graph, where "add this band" is the wrong offer.
  assert.match(
    body,
    /Boolean\(currentSearch\)\s*&&\s*matchCount\s*===\s*0/,
    'The card must be gated on BOTH a non-empty currentSearch AND ' +
      'matchCount === 0. A zero-result filter combination must not offer to ' +
      'add a band — the band may be in the tree and merely filtered out.'
  );
  // Hiding is the same code path, so a search that starts matching (or is
  // cleared) puts the card away without a separate teardown call.
  assert.match(
    body,
    /graphEmptyState\.hidden\s*=\s*!show/,
    'syncSearchEmptyState must drive the hidden attribute from the same ' +
      '`show` boolean, so results appearing or the query being cleared ' +
      'dismisses the card automatically.'
  );
  assert.match(
    body,
    /graphEmptyStateQuery\.textContent\s*=/,
    'syncSearchEmptyState must write the current query into ' +
      '#graph-empty-state-query so the card echoes what was searched for.'
  );
});

test('renderGraph syncs the empty state BEFORE its empty-node-set early return', () => {
  const callIndex = INDEX_HTML.indexOf('syncSearchEmptyState(filtered.nodes.length)');
  // Matched on the condition alone, not `if (!nodes.length) return;`: the
  // guard is now a block that logs the filter combination before returning.
  const earlyReturnIndex = INDEX_HTML.indexOf('if (!nodes.length)');
  assert.ok(
    callIndex > -1,
    'Expected renderGraph() to call syncSearchEmptyState(filtered.nodes.length).'
  );
  assert.ok(earlyReturnIndex > -1, "Expected renderGraph()'s `if (!nodes.length)` early return.");
  assert.ok(
    callIndex < earlyReturnIndex,
    'syncSearchEmptyState() must be called BEFORE the `if (!nodes.length)` early ' +
      'return. That early return is exactly the zero-result case the empty state ' +
      'exists for — calling after it means the card never appears.'
  );
});

test('both the desktop and the mobile search input re-render the graph, so both sync the card', () => {
  // The empty state piggy-backs on renderGraph(), so parity comes for free
  // as long as both inputs still call it. If either stops, mobile or desktop
  // silently loses the card.
  assert.match(
    INDEX_HTML,
    /getElementById\('node-search'\)\.addEventListener\('input',\s*event\s*=>\s*\{[\s\S]{0,200}renderGraph\(\)/,
    'The desktop #node-search input handler must still call renderGraph().'
  );
  assert.match(
    INDEX_HTML,
    /mobileSearch\.addEventListener\('input',\s*ev\s*=>\s*\{[\s\S]{0,200}renderGraph\(\)/,
    'The #mobile-node-search input handler must still call renderGraph(). ' +
      'This is what gives the empty state mobile parity.'
  );
});

