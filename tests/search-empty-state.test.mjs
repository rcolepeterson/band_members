test('stale "from your uploaded CSV" copy is gone', () => {
  // The graph is Neon-backed (/api/bands); the CSV is only a local
  // last-resort fallback. Telling users their data came from "your uploaded
  // CSV" was wrong on every real page load.
  assert.ok(
    !INDEX_HTML.includes('from your uploaded CSV'),
    'Expected the "from your uploaded CSV" copy to be gone. The data model is ' +
      'Neon-backed; nothing the user sees comes from an upload they performed.'
  );
});

test('the redundant #graph-note-* empty-state surface is gone', () => {
  // .graph-shell-footer was display:none !important globally (full-screen
  // stage pass), so #graph-note-left's "No matches yet." text had been
  // unreachable — a second, invisible empty-state surface competing with
  // #graph-badge. Consolidated away in favor of #graph-empty-state.
  assert.ok(
    !INDEX_HTML.includes('id="graph-note-left"'),
    'Expected #graph-note-left to be removed. It lived inside the globally ' +
      'display:none .graph-shell-footer, so its empty-state copy was dead ' +
      'weight competing with #graph-badge.'
  );
  assert.ok(
    !INDEX_HTML.includes('id="graph-note-right"'),
    'Expected #graph-note-right to be removed along with the footer it lived in.'
  );
  assert.ok(
    !/\bnoteLeft\b/.test(INDEX_HTML) && !/\bnoteRight\b/.test(INDEX_HTML),
    'Expected the noteLeft / noteRight variables and every write to them to be ' +
      'gone. Leaving them behind is a guaranteed null-deref once the spans are ' +
      'removed from the DOM.'
  );
  assert.ok(
    !/class="graph-shell-footer"/.test(INDEX_HTML),
    'Expected the .graph-shell-footer wrapper markup to be removed.'
  );
  // Dead selectors for a removed element are the same smell the
  // node-card__edit-btn cleanup called out.
  assert.ok(
    !/^\s*\.graph-shell-footer\s*[,{]/m.test(INDEX_HTML) && !/^\s*\.graph-note\s*\{/m.test(INDEX_HTML),
    'Expected the .graph-shell-footer / .graph-note CSS rules to be removed ' +
      'along with the markup they styled.'
  );
});

test('#graph-badge survives as the active-filter readout, distinct from the empty state', () => {
  // The two surfaces are NOT redundant with each other and both stay:
  //   #graph-badge      — which filters are currently applied.
  //   #graph-empty-state — the search came back with nothing.
  // A user can see "Search: heart · Grunge" in the badge while the card
  // explains that the combination matched nothing.
  assert.match(
    INDEX_HTML,
    /id="graph-badge"/,
    'Expected #graph-badge to still exist. It reports which filters are ' +
      'active, which is orthogonal to whether the result set is empty.'
  );
  assert.match(
    INDEX_HTML,
    /graphBadge\.textContent\s*=\s*badgeParts\.length\s*\?\s*badgeParts\.join\(' · '\)\s*:\s*'Full graph'/,
    'Expected #graph-badge to keep summarising the active filters ' +
      '("Full graph" when none). The empty state must not take this over.'
  );
});
