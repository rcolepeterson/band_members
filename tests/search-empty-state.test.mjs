// Tests for the search-miss empty state ("No Rawk Found") — backlog #21.
//
// What this locks in:
//
//   1. A zero-result SEARCH shows an empty-state card with the required
//      "No Rawk Found" headline and a CTA into the Add-band flow. A
//      zero-result *filter* combination does NOT — the band may well be in
//      the tree and simply filtered out, so offering to add it would be
//      wrong.
//   2. The card is a DOM overlay inside .graph-stage, a sibling of
//      #graph-svg. It is NOT drawn into the SVG, because renderGraph()
//      wipes the graph group and early-returns the moment the filtered node
//      set is empty — an in-SVG empty state would be erased by the exact
//      render that needs to show it.
//   3. Mobile parity. The card is not inside .graph-overlay-top (which is
//      display:none under 900px) and no media query hides it, so phones get
//      the same CTA. This is the PR #42/#44/#45/#63 trap.
//   4. The CTA routes through openSignupPopover() — the one existing funnel
//      that shows the sign-up gate to anonymous visitors and the Add-band
//      form to signed-in ones. No parallel gate.
//   5. Cleanup: the stale "from your uploaded CSV" copy is gone, and the
//      redundant #graph-note-left / #graph-note-right empty-state surface
//      (inside the globally display:none .graph-shell-footer) is gone with
//      it, leaving #graph-empty-state as the single search-miss surface and
//      #graph-badge as the single active-filter readout.
//
// Static HTML/JS regex checks in the same style as
// mobile-toolbar-parity.test.mjs and welcome-nudge-and-edit-cleanup.test.mjs
// — no browser, no DOM. The point is catching structural regressions in CI.

import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const INDEX_HTML = readFileSync(join(__dirname, '..', 'index.html'), 'utf8');

