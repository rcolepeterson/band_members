test('CTA opens the Add-band flow through the existing openSignupPopover funnel', () => {
  const fnMatch = INDEX_HTML.match(
    /function\s+openAddBandFromEmptyState\s*\(\s*\)\s*\{([\s\S]*?)\n\s{4}\}/
  );
  assert.ok(fnMatch, 'Expected function openAddBandFromEmptyState() in index.html.');
  const body = fnMatch[1];

  // One funnel for every "get me into the add/edit flow" affordance: the
  // welcome nudge CTA, the node-card sign-in hint, and now this. Signed-out
  // visitors get the sign-up gate inside #add-band-popover; signed-in
  // visitors get the form. Building a second gate here would drift.
  assert.match(
    body,
    /openSignupPopover\(\)/,
    'The empty-state CTA must call openSignupPopover(). For signed-out ' +
      'visitors that popover IS the sign-up gate, so this reuses the existing ' +
      'gate rather than adding a parallel one.'
  );
  // openSignupPopover() clicks the trigger, and that trigger toggles — so a
  // blind call would CLOSE an already-open popover.
  assert.match(
    body,
    /if\s*\(!popover\s*\|\|\s*popover\.hidden\)\s*openSignupPopover\(\)/,
    'openAddBandFromEmptyState must only call openSignupPopover() when ' +
      '#add-band-popover is closed. The Add-your-band trigger toggles, so ' +
      'clicking it while the popover is open would dismiss it.'
  );
  // Pre-fill only makes sense once the form is actually reachable.
  assert.match(
    body,
    /if\s*\(loadCurrentUser\(\)\)\s*prefillAddBandName\(currentSearch\)/,
    'Pre-fill must be gated on loadCurrentUser(). A signed-out visitor sees ' +
      'the sign-up gate, not the band form, so there is nothing to pre-fill yet.'
  );
});

test('CTA is wired to openAddBandFromEmptyState and stops the click from closing the popover', () => {
  assert.match(
    INDEX_HTML,
    /getElementById\('graph-empty-state-cta'\)\?\.addEventListener\('click',\s*event\s*=>\s*\{([\s\S]{0,400}?)\}\);/,
    'Expected a click listener bound to #graph-empty-state-cta.'
  );
  const handler = INDEX_HTML.match(
    /getElementById\('graph-empty-state-cta'\)\?\.addEventListener\('click',\s*event\s*=>\s*\{([\s\S]{0,400}?)\}\);/
  )[1];
  assert.match(
    handler,
    /event\.stopPropagation\(\)/,
    'The CTA handler must stopPropagation(). The document-level ' +
      '"click outside → close popovers" handler would otherwise dismiss the ' +
      'popover we just opened (same fix as the mobile Add-your-band trigger).'
  );
  assert.match(
    handler,
    /openAddBandFromEmptyState\(\)/,
    'The CTA handler must call openAddBandFromEmptyState().'
  );
});

test('pre-fill writes the search term into #band-name and lets the form revalidate', () => {
  const fnMatch = INDEX_HTML.match(
    /function\s+prefillAddBandName\s*\(\s*name\s*\)\s*\{([\s\S]*?)\n\s{4}\}/
  );
  assert.ok(fnMatch, 'Expected function prefillAddBandName(name) in index.html.');
  const body = fnMatch[1];
  assert.match(
    body,
    /getElementById\('band-name'\)/,
    'prefillAddBandName must target the existing #band-name input rather than ' +
      'introducing a new field.'
  );
  assert.match(body, /field\.value\s*=\s*name/, 'prefillAddBandName must set the field value.');
  // Setting .value programmatically fires no input event, so the form's
  // canonical-match / duplicate-band detection would never run on the
  // pre-filled name.
  assert.match(
    body,
    /dispatchEvent\(new Event\('input',\s*\{\s*bubbles:\s*true\s*\}\)\)/,
    "prefillAddBandName must dispatch an 'input' event so " +
      'validateSubmissionForm() runs its canonical-match and duplicate-band ' +
      'checks against the pre-filled name.'
  );
});

